def generate() -> None:
    rows: list[dict] = []

    # specialized：科目术语 × 模板
    for _subject, terms in SUBJECTS.items():
        for term in terms:
            for tpl in SPECIALIZED_TEMPLATES:
                rows.append({"text": tpl.format(t=term), "label": "specialized"})

    # general：手写 + 模板
    for s in GENERAL_SAMPLES:
        rows.append({"text": s, "label": "general"})
    for tpl, fillers in GENERAL_TEMPLATES:
        for filler in fillers:
            rows.append({"text": tpl.format(t=filler), "label": "general"})

    random.shuffle(rows)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    n_spec = sum(1 for r in rows if r["label"] == "specialized")
    n_gen = sum(1 for r in rows if r["label"] == "general")
    print(f"生成 {len(rows)} 行 → {OUT_PATH}")
    print(f"  general    = {n_gen}")
    print(f"  specialized= {n_spec}")


if __name__ == "__main__":
    generate()
