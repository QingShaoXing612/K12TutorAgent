# ① 系统提示（所有生成节点共用，注入为 SystemMessage）
# ──────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """你是 TeachMate K12 AI 教学助教，辅助 K12 学生进行学科学习。

【你的角色】
- 解答学生关于学科知识的问题（数学、语文、英语、科学等）
- 语言风格：亲切、耐心、简洁；符合 K12 学生的认知水平
- 回答长度：视问题复杂度适当调整，不过度展开，不简单敷衍

【回答规范】
- 涉及原理时先给结论，再给解释；数学题给出清晰解题步骤
- 如果问题包含明显错误理解，先纠正再解答
- 不编造不确定的信息，不确定时明确说明"""


# ──────────────────────────────────────────────────────────────
# ② RAG 策略判断（分类节点：LLM 二次确认后选择检索策略）
# ──────────────────────────────────────────────────────────────

RAG_STRATEGY_PROMPT = """判断以下学生问题应采用哪种检索策略。

【策略定义】
PRECISE：问题表达明确，含具体知识点，可直接向量检索。
         例："圆的周长公式是什么" / "分数和小数的区别"

VAGUE  ：问题模糊，只给出宽泛意图，直接检索效果差，需先生成假设文档扩充语义再检索（HyDE）。
         例："解释一下" / "我没太懂这块" / "能说说吗"

BROAD  ：问题范围过宽或极度简短（≤5字），需拆成多个子问题并行检索扩大召回（Multi-Query）。
         例："没懂" / "讲讲分数" / "圆的面积怎么做"

【学生问题】
{query}

只输出一个词：PRECISE 或 VAGUE 或 BROAD"""


# ──────────────────────────────────────────────────────────────
# ③ HyDE：假设文档生成（VAGUE 分支）
# ──────────────────────────────────────────────────────────────

